import { createFileRoute } from "@tanstack/react-router";
import { Clock, FileText, Sparkles } from "lucide-react";
import { Button } from "@/components/ui/button";
import { NexusCard, PageHeader, Pill, Section } from "@/components/nexus/shared";
import { AGENTS, type AgentStatus } from "@/lib/agents";
import { useIncident } from "@/lib/incident-store";

export const Route = createFileRoute("/assistants")({
  head: () => ({
    meta: [
      { title: "AI Agents — NexusDC" },
      { name: "description", content: "Six NVIDIA Nemotron-powered agents that analyze, simulate and propose infrastructure changes for approval." },
      { property: "og:title", content: "AI Agents — NexusDC" },
      { property: "og:description", content: "Six Nemotron-powered agents with transparent, sourced reasoning." },
      { property: "og:type", content: "website" },
      { name: "twitter:card", content: "summary_large_image" },
    ],
  }),
  component: Agents,
});

const statusTone = (s: AgentStatus) =>
  s === "Completed" ? "green" : s === "Failed" ? "red" : s === "Idle" ? "muted" : s === "Awaiting approval" ? "amber" : "blue";

function Agents() {
  const inc = useIncident();

  return (
    <div>
      <PageHeader badge="NVIDIA Nemotron" title="Six agents, one reviewed plan." sub="The agents analyze telemetry, predict failures, simulate interventions and estimate business impact. You approve every change." />

      {inc.phase === "idle" && (
        <div className="mb-8 flex flex-col items-start gap-3 rounded-2xl border border-destructive/30 bg-destructive/10 p-4 sm:flex-row sm:items-center">
          <p className="flex-1 text-sm">Agents are ready. Run Troubleshoot to analyze the facility and generate a proposed action plan.</p>
          <Button variant="hero" onClick={() => inc.setConfirmOpen(true)}><Sparkles /> Run Troubleshoot</Button>
        </div>
      )}
      {inc.phase === "plan" && (
        <div className="mb-8 flex flex-col items-start gap-3 rounded-2xl border border-primary/40 bg-primary/10 p-4 sm:flex-row sm:items-center">
          <p className="flex-1 text-sm">Analysis complete. A proposed action plan is waiting for your review — nothing has executed.</p>
          <Button variant="hero" onClick={() => inc.setPlanOpen(true)}>Review proposed plan</Button>
        </div>
      )}

      <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
        {AGENTS.map((a) => {
          const st = inc.agentStatus[a.name];
          const finding = inc.findings.find((f) => f.agent === a.name);
          return (
            <NexusCard
              key={a.name}
              icon={a.icon}
              title={a.name}
              line={finding ? finding.reasoning : a.role}
              action={
                <div className="flex flex-wrap items-center gap-2">
                  <Pill tone={statusTone(st)}>{st}</Pill>
                  {finding && (
                    <Pill tone={finding.reasoningSource === "nemotron" ? "blue" : "muted"}>
                      {finding.reasoningSource === "nemotron" ? "Nemotron reasoning" : "Fallback reasoning"}
                    </Pill>
                  )}
                </div>
              }
            >
              {finding ? (
                <div className="space-y-1 text-xs text-muted-foreground">
                  <p>Confidence {Math.round(finding.confidence * 100)}% · {finding.at}</p>
                  <p>{finding.observations[0]}</p>
                </div>
              ) : (
                <p className="flex items-center gap-1 text-xs text-muted-foreground"><Clock className="size-3" /> Waiting for a Troubleshoot run.</p>
              )}
            </NexusCard>
          );
        })}
      </div>

      <Section title="Agent activity">
        <div className="card-nexus p-6 hover:translate-y-0">
          {inc.feed.length === 0 ? (
            <p className="text-sm text-muted-foreground">No activity yet. Run Troubleshoot to watch the agents work.</p>
          ) : (
            <ol className="relative space-y-4 border-l border-border pl-6">
              {inc.feed.map((e, i) => (
                <li key={i} className="relative">
                  <span className="absolute -left-[31px] flex size-4 items-center justify-center rounded-full border border-primary bg-background" />
                  <p className="text-xs font-semibold uppercase tracking-wider text-primary">{e.agent}</p>
                  <p className="mt-0.5 text-sm">{e.text}</p>
                  <p className="mt-0.5 flex items-center gap-1 font-mono text-xs text-muted-foreground"><FileText className="size-3" /> {e.at}</p>
                </li>
              ))}
            </ol>
          )}
        </div>
        <p className="mt-3 text-xs text-muted-foreground">
          Reasoning text is generated by NVIDIA Nemotron through a secure server-side call; the key never reaches the browser. All numbers come from the telemetry model, not the AI. When the AI service is unreachable, agents use labeled fallback reasoning.
        </p>
      </Section>
    </div>
  );
}
